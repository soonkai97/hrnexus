// Renders tests/fixtures/payroll-calculator.json into docs/process/payroll-worked-examples.md, the accountant review pack.
// The expected figures in the fixture are worked out by hand (the formula is in each example's "working"), not generated
// by the calculator, so the pack is an independent calculation the accountant can check line by line.
// Usage: node scripts/render-payroll-worked-examples.mjs        (writes the file)
// The test scripts/payroll-worked-examples.test.mjs fails when the file is out of date with the fixture.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const FIXTURE = path.join(root, 'tests', 'fixtures', 'payroll-calculator.json');
export const OUTPUT = path.join(root, 'docs', 'process', 'payroll-worked-examples.md');

// Culture-invariant on purpose: toFixed never uses the machine's locale.
const group = (digits) => digits.replace(/\B(?=(\d{3})+(?!\d))/g, ',');
const rm = (n) => {
  const [whole, sen] = Number(n).toFixed(2).split('.');
  return `RM${group(whole)}.${sen}`;
};
const pct = (n) => `${parseFloat((Number(n) * 100).toFixed(4))}%`;

const ROUNDING = {
  none: 'no rounding',
  'nearest-cent': 'to the nearest sen',
  'nearest-5-sen': 'to the nearest 5 sen',
  'up-to-next-ringgit': 'up to the next ringgit',
};

const LINE_LABELS = {
  'unpaid-leave': 'Unpaid-leave deduction',
  'epf-employee': 'EPF, employee',
  'epf-employer': 'EPF, employer',
  'socso-employee': 'SOCSO, employee',
  'socso-employer': 'SOCSO, employer',
  'eis-employee': 'EIS, employee',
  'eis-employer': 'EIS, employer',
  'hrd-levy': 'HRD Corp levy (employer)',
  pcb: 'PCB (typed in)',
};

function rateRow(r) {
  const parts = [`employee ${pct(r.employeeRate ?? 0)}`, `employer ${pct(r.employerRate ?? 0)}`];
  if (r.employerRateMode === 'whole-wage-by-threshold')
    parts[1] = `employer ${pct(r.employerRate)} if the wage base is up to ${rm(r.employerRateThreshold)}, otherwise ${pct(r.employerRateAbove)} on the whole wage base`;
  if (r.wageCeiling) parts.push(`wages counted up to ${rm(r.wageCeiling)}`);
  parts.push(ROUNDING[r.rounding] ?? r.rounding);
  return `| ${r.scheme} | ${parts.join('; ')} | ${r.note ?? ''} |`;
}

function vectorBlock(v, n) {
  const e = v.expected;
  const lines = [];
  lines.push(`### Example ${n}: ${v.name}`);
  lines.push('');
  lines.push('**How it is worked out**');
  lines.push('');
  for (const w of v.working) lines.push(`- ${w}`);
  lines.push('');
  lines.push('| Figure | Amount |');
  lines.push('| --- | ---: |');
  lines.push(`| Prorated basic | ${rm(e.proratedBasic)} |`);
  if (e.unpaidLeave) lines.push(`| Unpaid-leave deduction | ${rm(e.unpaidLeave)} |`);
  lines.push(`| **Gross** | **${rm(e.gross)}** |`);
  for (const [key, amount] of Object.entries(e.lines)) {
    if (key === 'unpaid-leave') continue;
    lines.push(`| ${LINE_LABELS[key] ?? key} | ${rm(amount)} |`);
  }
  if (e.deductionsApplied)
    e.deductionsApplied.forEach((a, i) =>
      lines.push(`| Other deduction ${i + 1} applied | ${rm(a)} |`),
    );
  if (e.unapplied)
    lines.push(`| Other deductions not applied (carried to next month) | ${rm(e.unapplied)} |`);
  lines.push(`| **Net pay** | **${rm(e.net)}** |`);
  lines.push(`| **Employer cost** | **${rm(e.employerCost)}** |`);
  lines.push('');
  lines.push('Accountant: ☐ correct  ☐ needs a change: ______________________');
  lines.push('');
  return lines.join('\n');
}

export function render(fixture) {
  const out = [];
  out.push('# Payroll worked examples: accountant review pack');
  out.push('');
  out.push(
    '> **Generated** from `tests/fixtures/payroll-calculator.json` by `node scripts/render-payroll-worked-examples.mjs`. Do not edit this file by hand; change the fixture and regenerate.',
  );
  out.push('');
  out.push('## What this is');
  out.push('');
  out.push(
    'HRNexus calculates a monthly payslip in a fixed order: prorated basic salary, unpaid-leave deduction, gross, the statutory contributions, the tax deduction (typed in), other deductions, net pay and employer cost. Each example below is a small month worked **by hand**, with the formula shown. The program is tested to produce exactly these figures from the rates in the first table.',
  );
  out.push('');
  out.push(
    '**Please check two things:** (1) that the **rates and rounding rules** in the first table are the official ones, and (2) that each **example** is how you would calculate it. Anything wrong is a change to data and to the examples, not to the program. See also `docs/process/payroll-accountant-questions.md`.',
  );
  out.push('');
  out.push(
    'Every rate here is **unverified** (taken from the requirements document, researched 13 Nov 2026; the percentages are placeholders for the official band tables, and the rounding rules are assumptions).',
  );
  out.push('');
  out.push('## Rates used in these examples');
  out.push('');
  out.push('| Scheme | Rule | Note |');
  out.push('| --- | --- | --- |');
  for (const r of fixture.rates) out.push(rateRow(r));
  out.push('');
  out.push('## Examples');
  out.push('');
  fixture.vectors.forEach((v, i) => out.push(vectorBlock(v, i + 1)));
  return out.join('\n');
}

export async function renderFormatted(fixture) {
  const config = (await prettier.resolveConfig(OUTPUT)) ?? {};
  return prettier.format(render(fixture), { ...config, parser: 'markdown' });
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const fixture = JSON.parse(fs.readFileSync(FIXTURE, 'utf8'));
  fs.writeFileSync(OUTPUT, await renderFormatted(fixture));
  console.log(`Wrote ${path.relative(root, OUTPUT)} (${fixture.vectors.length} examples).`);
}
